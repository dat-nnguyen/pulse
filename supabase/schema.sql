-- Policies for Storage Bucket Objects
create policy "Allow public read of audio files"
on storage.objects for select
using (bucket_id = 'audio-files');

create policy "Allow public upload to audio files"
on storage.objects for insert
with check (bucket_id = 'audio-files');

create policy "Allow public update to audio files"
on storage.objects for update
using (bucket_id = 'audio-files');

create policy "Allow public delete of audio files"
on storage.objects for delete
using (bucket_id = 'audio-files');
